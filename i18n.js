function unitName(entity) {
  if (!entity) return "";
  if (state.lang === "ko") return entity.unit;
  const table = SHORT_UNIT[state.lang];
  if (table && table[entity.code]) return table[entity.code];
  return entity.code;
}

function withUnit(amountText, entity) {
  const unit = unitName(entity);
  if (["ko", "ja", "zh", "zh-Hant"].includes(state.lang)) return `${amountText}${unit}`;
  return `${amountText} ${unit}`;
}

function priceLabel(name) {
  if (state.lang === "ko") return name;
  const row = PRICE[name];
  if (!row) return name;
  return row[state.lang] || row.en || name;
}
