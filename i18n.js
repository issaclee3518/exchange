function intlLocale() {
  if (state.lang === "zh-Hant") return "zh-Hant";
  if (state.lang === "zh") return "zh-Hans";
  return state.lang || "en";
}

function languageForVisitor(country) {
  const browser = ((navigator.languages && navigator.languages[0]) || navigator.language || "en").toLowerCase();
  const base = browser.split("-")[0];
  const region = (browser.split("-")[1] || "").toUpperCase();
  if (base === "zh") {
    if (["TW", "HK", "MO"].includes(region) || browser.includes("hant")) return "zh-Hant";
    return "zh";
  }
  if (country) {
    const options = MULTI_LANG[country.iso] || [];
    if (options.includes(base) && STRINGS[base]) return base;
    if (options.includes("zh-Hant") && base === "zh") return "zh-Hant";
    const mapped = COUNTRY_LANG[country.iso];
    if (mapped && STRINGS[mapped]) return mapped;
  }
  if (STRINGS[base]) return base;
  return "en";
}

function t(key, vars) {
  const chain = [state.lang];
  if (state.lang === "zh-Hant") chain.push("zh");
  chain.push("en");
  let text = key;
  for (const lang of chain) {
    if (STRINGS[lang] && STRINGS[lang][key]) {
      text = STRINGS[lang][key];
      break;
    }
  }
  if (vars) {
    Object.entries(vars).forEach(([name, value]) => {
      text = text.replaceAll(`{${name}}`, value);
    });
  }
  return text;
}

let regionNamesCache = null;
let currencyNamesCache = null;
let namesLocale = "";

function nameTools() {
  const locale = intlLocale();
  if (namesLocale !== locale) {
    namesLocale = locale;
    regionNamesCache = new Intl.DisplayNames([locale], { type: "region" });
    currencyNamesCache = new Intl.DisplayNames([locale], { type: "currency" });
  }
  return { region: regionNamesCache, currency: currencyNamesCache };
}

function currencyName(code) {
  if (!code) return "";
  if (state.lang === "ko") {
    const currency = currencyByCode(code);
    return currency ? currency.nameKo : code;
  }
  try {
    return nameTools().currency.of(code) || code;
  } catch (error) {
    return code;
  }
}

function placeName(entity) {
  if (!entity) return "";
  if (entity.isCurrency || String(entity.id || "").startsWith("cur:")) return currencyName(entity.code);
  if (state.lang === "ko") return entity.name;
  if (entity.iso) {
    try {
      const label = nameTools().region.of(entity.iso);
      if (label && label !== entity.iso) return label;
    } catch (error) {
      return state.lang === "ko" ? entity.name : (entity.nameEn || entity.name);
    }
  }
  return state.lang === "ko" ? entity.name : (entity.nameEn || entity.name);
}

